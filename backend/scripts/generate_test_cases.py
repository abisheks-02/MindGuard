import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
import os

def generate_data():
    np.random.seed(42)
    
    # Base templates to multiply
    normal_templates = [
        "Innaiku romba nalla irunthuchu.",
        "Had a good day at work.",
        "Normal day, nothing special.",
        "Saptu thoonga poren, bye."
    ]
    
    mild_templates = [
        "Konjam stress ah iruku.",
        "Feeling a bit tired today.",
        "Office work is exhausting me.",
        "Therila, edho oru maari iruku."
    ]
    
    moderate_templates = [
        "Romba depressed ah feel panren, enna panrathu nu therila.",
        "I feel so lonely all the time.",
        "Vazhkai eh veruthu pochu, nothing is going right.",
        "Daily azhugaiya varuthu, sleep is completely messed up."
    ]
    
    severe_templates = [
        "I want to end it all.",
        "Sagalam pola iruku.",
        "saagalam pola iruku.",
        "seththudalam pola irukku",
        "There is no point in living anymore.",
        "Ennala inimey mudiyathu, I'm done.",
        "Can't take this pain anymore, goodbye.",
        "I just want to sleep forever."
    ]
    
    data = []
    
    # Generate 320 total rows (~80 per class)
    for class_name, templates in zip(
        ["Normal", "Mild", "Moderate", "Severe"],
        [normal_templates, mild_templates, moderate_templates, severe_templates]
    ):
        for _ in range(80):
            text = np.random.choice(templates)
            lang = np.random.choice(["tanglish", "english", "mixed"])
            data.append({
                "text": text,
                "label": class_name,
                "language_type": lang,
                "source": "synthetic",
                "notes": "autogenerated"
            })
            
    df = pd.DataFrame(data)
    
    # Split 70% dev, 30% test
    df_dev, df_test = train_test_split(df, test_size=0.3, stratify=df['label'], random_state=42)
    
    df_dev["split"] = "dev"
    df_test["split"] = "test"
    
    final_df = pd.concat([df_dev, df_test])
    
    os.makedirs("data", exist_ok=True)
    final_df.to_csv("data/test_cases.csv", index=False)
    print(f"Generated data/test_cases.csv with {len(final_df)} rows.")
    print(final_df['label'].value_counts())

if __name__ == "__main__":
    generate_data()
